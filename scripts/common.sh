#!/bin/bash
# scripts/common.sh — env bootstrap + shared helpers
# (get_node_ip/wait_for_k3s_cluster) for the retained bash scripts.
[[ "${INFRA_LIB_LOADED:-}" = true ]] && return 0
INFRA_LIB_LOADED=true

_lib_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" >/dev/null 2>&1 && pwd)"

# ---- always-on environment (exported so child processes in a chain see it) ----
# Pre-set values win (in-cluster pods ship INFRA_ROOT/MY_UID in
# their env and must not get host paths recomputed over them).
if [ -z "${INFRA_ROOT:-}" ]; then
    INFRA_ROOT="$(cd "$_lib_dir/.." >/dev/null 2>&1 && pwd)"
fi
export INFRA_ROOT
[ -n "${COMPOSE_STATE_DIR:-}" ] || export COMPOSE_STATE_DIR="$INFRA_ROOT/current_target/compose_live_state"

get_node_ip() {
    local iface
    iface=$(ip -4 route show default 2>/dev/null | awk '{print $5; exit}')
    [ -n "$iface" ] || return 1
    ip -4 addr show "$iface" | grep -oP 'inet \K[\d.]+'
}

wait_for_k3s_cluster() {
    local timeout_secs="${1:-150}"
    local max_tries=$(( timeout_secs / 5 ))
    for i in $(seq 1 "$max_tries"); do
        if kubectl get nodes >/dev/null 2>&1; then
            echo "Cluster ready."
            return 0
        fi
        echo "Waiting... ($i/$max_tries)"
        sleep 5
    done
    echo "Error: Could not connect to Kubernetes cluster after ${timeout_secs} seconds." >&2
    return 1
}

set_my_uid() {
    if [ -z "${MY_UID:-}" ]; then
        if [ "$(id -u)" -eq 0 ]; then
            export MY_UID=1000
        else
            MY_UID="$(id -u)"
            export MY_UID
        fi
    fi
}

# ensure_machine_env <target> — write the Compose machine-fact .env for a
# target. This is deliberately generated, not hand-edited: it makes the
# per-host UID/GID/username available to every Compose project and keeps config
# env files free of machine facts.
ensure_machine_env() {
    local target="${1:-}"
    local target_dir my_username docker_gid
    [ -n "$target" ] || return 1
    target_dir="$INFRA_ROOT/targets/$target"
    [ -d "$target_dir/compose" ] || return 0

    set_my_uid
    docker_gid="$(getent group docker | cut -d: -f3 || true)"
    my_username="$(getent passwd "$MY_UID" 2>/dev/null | cut -d: -f1 || true)"
    [ -n "$my_username" ] || my_username="${SUDO_USER:-${USER:-}}"

    {
        echo "# Machine facts — generated by scripts/common.sh; do not edit."
        echo "MY_UID=$MY_UID"
        echo "DOCKER_GID=$docker_gid"
        echo "MY_USERNAME=$my_username"
    } >"$target_dir/compose/.env"
    chmod 600 "$target_dir/compose/.env"
}

# require_target — export TARGET from the first argument. Warns (does not fail)
# when this machine's hostname differs, so check flows like validate can run
# for any target from any checkout.
require_target() {
    _require_target "$1"
    if [ "$(hostname)" != "$TARGET" ]; then
        echo "Warning: hostname '$(hostname)' does not match target '$TARGET'." >&2
        echo "Deploying may apply the wrong configuration." >&2
    fi
}

# require_target_host — like require_target, but hard-fails when this machine's
# hostname does not match the target (compose ops run on the target machine).
require_target_host() {
    _require_target "$1"
    if [ "$(hostname)" != "$TARGET" ]; then
        echo "Error: running on host '$(hostname)' but target is '$TARGET'." >&2
        exit 1
    fi
}

# _require_target — validate the target name and export TARGET (no hostname check).
_require_target() {
    local t="${1:-}"
    if [ -z "$t" ]; then
        echo "Error: usage: $(basename "$0") <target>" >&2
        exit 1
    fi
    if [ ! -d "$INFRA_ROOT/targets/$t" ]; then
        echo "Error: unknown target '$t' — targets: $(find "$INFRA_ROOT/targets" -mindepth 1 -maxdepth 1 -type d ! -name templates -printf '%f ' 2>/dev/null)" >&2
        exit 1
    fi
    export TARGET="$t"
    set_my_uid
}

# shellcheck source=scripts/config.sh
. "$INFRA_ROOT/scripts/config.sh"
